export const generateRealtimeAlert = () => {
  const types = [
    { type: 'mobile_phone', label: 'Mobile Phone Detected Near Loom', severity: 'critical' },
    { type: 'smoking', label: 'Smoking Detected', severity: 'critical' },
    { type: 'drowsiness', label: 'Worker Drowsiness Alert', severity: 'warning' },
    { type: 'unauthorized_entry', label: 'Unauthorized Entry', severity: 'critical' },
    { type: 'fire_extinguisher', label: 'Fire Extinguisher Missing', severity: 'warning' },
  ];

  const cameras = ['CAM-001', 'CAM-002', 'CAM-003', 'CAM-004', 'CAM-005', 'CAM-006'];
  const zones = ['Loom Section', 'Restricted Zone', 'Warehouse', 'Chemical Storage', 'Production Line', 'Supervisor Office'];

  const randomType = types[Math.floor(Math.random() * types.length)];
  const randomCamera = cameras[Math.floor(Math.random() * cameras.length)];
  const randomZone = zones[Math.floor(Math.random() * zones.length)];

  return {
    id: `ALT-${Date.now()}`,
    timestamp: new Date().toISOString(),
    camera: randomCamera,
    zone: randomZone,
    violationType: randomType.type,
    violationLabel: randomType.label,
    severity: randomType.severity,
    confidence: (Math.random() * 0.2 + 0.8).toFixed(2),
    status: 'active',
    snapshot: `/api/snapshots/alt-${Date.now()}.jpg`,
    acknowledged: false,
    resolvedBy: null,
    notes: '',
  };
};
